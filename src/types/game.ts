export type CharacterId = 'N' | 'R' | 'B' | 'V' | 'T' | 'O' | 'S';

export type Expression = 'neutral' | 'happy' | 'alert' | 'smirk' | 'sad';

export type MouthShape = 'closed' | 'mid' | 'open' | 'round';

export type MaterialId = 'ti' | 'he3' | 'si' | 'xe' | 'qc';

export type SceneBackdropId =
  | 'station_bridge'
  | 'launchpad_dusk'
  | 'leo_storm'
  | 'lunar_crater'
  | 'lagrange_sun'
  | 'mars_canyon'
  | 'asteroid_belt'
  | 'europa_ice'
  | 'titan_haze'
  | 'neptune_gate';

export interface CharacterDef {
  id: CharacterId;
  name: string;
  role: string;
  bio: string;
  specialty: string;
  voicePitch: number;
  voiceType: OscillatorType;
  accentColor: string;
  palette: Record<string, string>;
  sprites: Record<Expression, string[]>;
  mouthRow: number;
  eyeRows: number[];
  identityLabel: string;
}

export interface DialogueLine {
  speaker: CharacterId | null;
  expression?: Expression;
  side?: 'left' | 'right';
  backdrop?: SceneBackdropId;
  caption?: string;
  text: string;
  sfx?: 'alert' | 'signal' | 'chime' | 'boom' | 'none';
}

export interface MaterialDef {
  id: MaterialId;
  symbol: string;
  name: string;
  color: string;
  description: string;
  scienceNote: string;
}

export interface HullPart {
  id: string;
  name: string;
  cost: number;
  massTons: number;
  fuelCapacity: number; // affects Tsiolkovsky mass ratio
  reliability: number; // 0..1
  powerGen: number; // Watts generated by hull bus/solar
  maxInstruments: number;
  unlockMission?: number; // 0-indexed mission unlock
  unlockUpgrade?: { id: UpgradeId; level: number };
  visualTier: number; // 0..4
  description: string;
  scienceNote: string;
}

export interface EnginePart {
  id: string;
  name: string;
  cost: number;
  massTons: number;
  thrustKN: number; // Determines TWR at liftoff
  isp: number; // Specific Impulse (seconds) -> Delta-V!
  powerDraw: number; // Electric engines draw Watts
  unlockMission?: number;
  unlockUpgrade?: { id: UpgradeId; level: number };
  flameColor: string;
  description: string;
  scienceNote: string;
}

export interface InstrumentPart {
  id: string;
  name: string;
  cost: number;
  massTons: number;
  powerDraw: number;
  scienceBase: number;
  specialtyTag: 'optics' | 'radar' | 'spectro' | 'plasma' | 'quantum';
  unlockMission?: number;
  unlockUpgrade?: { id: UpgradeId; level: number };
  description: string;
  scienceNote: string;
}

export interface ShieldPart {
  id: string;
  name: string;
  cost: number;
  massTons: number;
  powerDraw: number;
  hazardResist: number; // 0..0.55 bonus reliability & shield charge
  shieldCharges: number; // active charges in orbital flight
  unlockMission?: number;
  unlockUpgrade?: { id: UpgradeId; level: number };
  description: string;
  scienceNote: string;
}

export type UpgradeId = 'budget' | 'propulsion' | 'telemetry' | 'metallurgy' | 'shielding' | 'quantum';

export interface UpgradeDef {
  id: UpgradeId;
  name: string;
  maxLevel: number;
  baseCredits: number;
  materialCosts: Array<Partial<Record<MaterialId, number>>>; // per level 1..5
  effectSummary: string;
  scienceNote: string;
}

export interface AnomalyChoice {
  label: string;
  sublabel: string;
  safeMode: boolean;
  baseSuccessProb: number; // 0..1
  bonusSource?: 'shield' | 'power' | 'dv' | 'radar';
  successSciMult: number;
  failSciMult: number;
  successNarrative: string;
  failNarrative: string;
  scienceLogic: string;
}

export interface MissionAnomaly {
  title: string;
  speaker: CharacterId;
  prompt: string;
  scienceContext: string;
  choices: [AnomalyChoice, AnomalyChoice];
}

export interface MissionDef {
  id: number;
  code: string;
  name: string;
  destination: string;
  targetType: string;
  backdrop: SceneBackdropId;
  budget: number;
  reqDeltaV: number; // km/s
  reqTWR: number; // Thrust-to-Weight ratio minimum
  reqScience: number;
  hazardLevel: 'Low' | 'Moderate' | 'High' | 'Severe' | 'Extreme';
  hazardType: string;
  recommendedTag: InstrumentPart['specialtyTag'];
  rewards: {
    credits: number;
    materials: Partial<Record<MaterialId, number>>;
  };
  scienceBrief: string;
  orbitalLogic: string;
  preCutscene: DialogueLine[];
  postCutscene: DialogueLine[];
  anomaly: MissionAnomaly;
  unlocksCodex: string[];
}

export interface CodexEntry {
  id: string;
  title: string;
  category: 'Propulsion' | 'Astrophysics' | 'Materials' | 'Signal Mystery';
  formula?: string;
  summary: string;
  deepDive: string;
  inGameImpact: string;
}

export interface RocketConfig {
  hullId: string;
  engineId: string;
  instrumentIds: string[];
  shieldId: string | null;
}

export interface ComputedRocketStats {
  totalCost: number;
  budgetLimit: number;
  dryMass: number;
  wetMass: number;
  twr: number;
  deltaV: number;
  powerNet: number; // gen - draw
  powerGen: number;
  powerDraw: number;
  scienceOutput: number;
  reliability: number; // 0..0.99
  shieldCharges: number;
  canLaunch: boolean;
  issues: string[];
  novaTip: string;
}

export interface SaveState {
  credits: number;
  materials: Record<MaterialId, number>;
  missionStars: number[]; // length 8, 0..3
  upgrades: Record<UpgradeId, number>;
  streak: number;
  seenIntro: boolean;
  unlockedCodex: string[];
  totalScienceCollected: number;
  missionsCompleted: number;
}

export type ScreenMode =
  | 'TITLE'
  | 'CUTSCENE'
